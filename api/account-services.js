// Shared "Account Issue" lock response — only used for the 'full' restriction
// level, since 'transfers_only' accounts should keep using these services.
function restrictedResponse(res) {
  return res.status(403).json({
    error: 'There is an issue on this account that requires in-person verification at a branch. Please visit any of our branches with a valid ID to resolve this issue.',
    accountRestricted: true,
  });
}

function generateStatementPdf({ accountHolder, accountType, accountNumber, periodStart, periodEnd, openingBalance, closingBalance, lineItems }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'LETTER' });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const money = (n) => `$${Number(n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    const dateFmt = (d) => new Date(d).toLocaleDateString('en-US', { month: 'short', day: '2-digit', year: 'numeric' });
    const maskedAcct = accountNumber ? '•••• ' + String(accountNumber).slice(-4) : '••••';
    const accountLabel = accountType === 'checking' ? 'Primary Checking' : 'High-Yield Savings';

    // Letterhead
    doc.fillColor('#0f172a').fontSize(20).font('Helvetica-Bold').text('APEX HORIZON BANK');
    doc.fontSize(9).fillColor('#10b981').font('Helvetica-Bold').text('FEDERAL MOBILE BANKING', { characterSpacing: 1 });
    doc.moveDown(1);
    doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(50, doc.y).lineTo(562, doc.y).stroke();
    doc.moveDown(1);

    doc.fillColor('#0f172a').fontSize(14).font('Helvetica-Bold').text('Account Statement');
    doc.fontSize(9).fillColor('#64748b').font('Helvetica').text(`${dateFmt(periodStart)} — ${dateFmt(periodEnd)}`);
    doc.moveDown(0.75);

    doc.fontSize(10).fillColor('#334155').font('Helvetica-Bold').text('Account Holder: ', { continued: true }).font('Helvetica').text(accountHolder);
    doc.font('Helvetica-Bold').text('Account: ', { continued: true }).font('Helvetica').text(`${accountLabel} ${maskedAcct}`);
    doc.moveDown(1);

    // Summary box
    const summaryTop = doc.y;
    doc.rect(50, summaryTop, 512, 60).fill('#f8fafc');
    doc.fillColor('#0f172a');
    doc.fontSize(9).font('Helvetica-Bold').text('OPENING BALANCE', 65, summaryTop + 12);
    doc.fontSize(13).font('Helvetica-Bold').text(money(openingBalance), 65, summaryTop + 28);

    doc.fontSize(9).font('Helvetica-Bold').fillColor('#0f172a').text('CLOSING BALANCE', 230, summaryTop + 12);
    doc.fontSize(13).font('Helvetica-Bold').fillColor('#10b981').text(money(closingBalance), 230, summaryTop + 28);

    const netChange = closingBalance - openingBalance;
    doc.fontSize(9).font('Helvetica-Bold').fillColor('#0f172a').text('NET CHANGE', 395, summaryTop + 12);
    doc.fontSize(13).font('Helvetica-Bold').fillColor(netChange >= 0 ? '#10b981' : '#dc2626').text((netChange >= 0 ? '+' : '') + money(netChange), 395, summaryTop + 28);

    doc.y = summaryTop + 75;
    doc.fillColor('#0f172a');
    doc.moveDown(0.5);

    // Transaction table
    doc.fontSize(9).font('Helvetica-Bold').fillColor('#64748b');
    const tableTop = doc.y;
    doc.text('DATE', 50, tableTop, { width: 70 });
    doc.text('DESCRIPTION', 125, tableTop, { width: 240 });
    doc.text('AMOUNT', 370, tableTop, { width: 90, align: 'right' });
    doc.text('BALANCE', 465, tableTop, { width: 97, align: 'right' });
    doc.moveTo(50, tableTop + 14).lineTo(562, tableTop + 14).strokeColor('#cbd5e1').stroke();

    let y = tableTop + 22;
    doc.font('Helvetica').fontSize(9);

    if (lineItems.length === 0) {
      doc.fillColor('#94a3b8').text('No transactions during this period.', 50, y);
      y += 20;
    } else {
      lineItems.forEach((item) => {
        if (y > 700) {
          doc.addPage();
          y = 50;
        }
        const isOut = item.amount < 0;
        doc.fillColor('#334155').text(dateFmt(item.date), 50, y, { width: 70 });
        doc.text(item.description || '—', 125, y, { width: 240 });
        doc.fillColor(isOut ? '#0f172a' : '#10b981').text((isOut ? '-' : '+') + money(Math.abs(item.amount)), 370, y, { width: 90, align: 'right' });
        doc.fillColor('#334155').text(money(item.balance), 465, y, { width: 97, align: 'right' });
        y += 18;
      });
    }

    doc.fontSize(8).fillColor('#94a3b8').text(
      'This statement is generated by Apex Horizon Bank for informational purposes. For questions about your account, contact support through the app.',
      50, 730, { width: 512 }
    );

    doc.end();
  });
}

